import numpy as np
# Diferentemente das listas padrão do Python, os arrays NumPy são projetados para armazenar elementos do mesmo tipo de dado,
# o que permite operações matemáticas muito mais rápidas e eficientes. 

array1= np.array([1, 2, 3, 4, 5, 6])
print(f"Array criado a partir de uma lista: {array1}")

array2= np.array((10, 20, 30, 40, 50, 60))
print(f"Arreya criado a partir de uma tupla: {array2}")