import numpy as np

# Matriz 2x3 (2 linha, 3 colunas):

matriz_2x3= np.array([[1, 2, 3], [20, 4, 7]])
print("Matriz 2x3: \n", matriz_2x3)
# Esta matriz pode representar, por exemplo, dados de duas amostras com três características cada.

# Matriz 3x2 (3 linhas, 2 colunas):

matriz_3x2= np.array([[1,2], [3,4], [5,6]])
print("Matriz 3x2: \n", matriz_3x2)
# Útil para representar relações ou transformações em espaços bidimensionais.